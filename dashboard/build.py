"""
Builds every copy of the dashboard from index.src.html:
  pi/dashboard.html            served by the Raspberry Pi (rig_server.py)
  usb/gmach_dashboard.html     stand-alone file, Mega on a USB cable (Chrome/Edge)
  esp32/rig_bridge/index_html.h  embedded in the ESP32 bridge sketch
Run after editing index.src.html:   python3 dashboard/build.py
"""
import pathlib

here = pathlib.Path(__file__).resolve().parent
repo = here.parent
logo = (here / "logo.b64").read_text().strip()
src = (here / "index.src.html").read_text().replace("__LOGO__", logo)
net = src.replace("__USBONLY__", "false")
usb = src.replace("__USBONLY__", "true")
assert ")rawliteral" not in net

(repo / "pi" / "dashboard.html").write_text(net)
(repo / "usb" / "gmach_dashboard.html").write_text(usb)
(repo / "esp32" / "rig_bridge" / "index_html.h").write_text(
    "// generated by dashboard/build.py from dashboard/index.src.html - do not edit by hand\n"
    "#pragma once\n#include <pgmspace.h>\n"
    "const char INDEX_HTML[] PROGMEM = R\"rawliteral(" + net + ")rawliteral\";\n")
print("built pi/dashboard.html, usb/gmach_dashboard.html, esp32/rig_bridge/index_html.h")
